export function getSourceBySlug(slug) {
  if (!slug) return null;
  const clean = slug.toLowerCase().trim();
  return SOURCES.find(
    s => s.slug === clean || s.id === clean || (s.aliases && s.aliases.includes(clean))
  ) || null;
}
